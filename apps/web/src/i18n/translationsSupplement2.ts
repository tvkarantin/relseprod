const EN_PATTERNS: Array<[RegExp, (...parts: string[]) => string]> = [
  [/^Всего рилсов:$/, () => 'Total reels:'],
  [/^Обновлено сегодня в (.+)$/, (time) => `Updated today at ${time}`],
  [/^Страница (\d+)$/, (page) => `Page ${page}`],
  [/^Открыть видео на YouTube: (.+)$/, (title) => `Open YouTube video: ${title}`],
  [/^Рейтинг (\d+)$/, (score) => `Score ${score}`],
  [/^(\d[\d\s.,]*) просмотров$/, (count) => `${count} views`],
  [/^(\d+) результатов$/, (count) => `${count} results`],
  [/^Удалить (.+)$/, (name) => `Delete ${name}`],
  [/^порог (\d+)$/, (score) => `threshold ${score}`],
  [/^Каналов в проверке: (\d+)$/, (count) => `Channels checked: ${count}`],
  [/^от (.+) просмотров$/, (count) => `from ${count} views`],
  [/^за (\d+) дн\.$/, (days) => `last ${days} days`],
  [/^Последняя проверка: (.+)$/, (date) => `Last check: ${date}`],
  [/^Прогресс проверки темы (.+)$/, (name) => `Topic check progress: ${name}`],
  [/^Последние 20 рилс - (.+)$/, (name) => `Latest 20 reels — ${name}`],
  [/^Сценарий экспортирован в формате (.+)! 💾$/, (format) => `Script exported as ${format}! 💾`],
  [/^Сценарий запланирован для публикации в (.+)! 🚀$/, (platform) => `Script scheduled for ${platform}! 🚀`],
  [/^Конкурент (.+) успешно добавлен!$/, (name) => `Competitor ${name} added successfully!`],
  [/^Открываем оригинал от (.+)\.\.\.$/, (name) => `Opening original from ${name}...`],
]

export function translateSupplement2(value: string, language: AppLanguage): string {
  if (language === 'ru' || !value) return value
  const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/)
  if (!match) return value
  const [, before, core, after] = match

  const exact = EN_TEXT[core]
  if (exact !== undefined) return `${before}${exact}${after}`

  for (const [pattern, formatter] of EN_PATTERNS) {
    const result = core.match(pattern)
    if (result) return `${before}${formatter(...result.slice(1))}${after}`
  }

  return value
}
